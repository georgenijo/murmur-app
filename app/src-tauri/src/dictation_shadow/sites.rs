//! The dictation lock D's acquisition sites (D-S2c-9 a, D-S2c-15 S3 and its review).
//!
//! The live shell counts every acquisition of D inside the guard function
//! (`MutexExt::lock_or_recover`), while armed. Most take D without taking a decision
//! section (a read of three fields, a fence held across a paste, the overlay's
//! `get_status`): they owe no header. [`site_rules.in`](site_rules.in) says which is which
//! (named sites, and the rule that an acquisition in a function that never calls the
//! capture API cannot produce a header), and `build.rs` applies it to every source file
//! to generate the build's complete site map ([`lookup`]).
//!
//! * Test builds apply the rules in the guard ([`classify`] reads the source), so a named
//!   or test site is not counted at all.
//! * A native build counts each acquisition at its location in a fixed lock-free table
//!   ([`note`]: a few atomics, no allocation, no lock, no wait) and the comparison thread
//!   looks the table up in the map when it writes the summary ([`report`]). The entries
//!   reported are the table's total less its non-family part (`conservation.non_family`,
//!   by `file:line`), both from the one snapshot: a read another thread makes while the
//!   summary is written is in both or in neither. A location the map does not name stays
//!   in the entries and is counted as unclassified, so it unbalances the books instead of
//!   hiding.
//!
//! The books are reconciled in total, not by site: the entry, the header and the outcome
//! of one decision are counted by different code with no shared site, and attributing
//! them needs a site argument at each capture entry in `commands/recording.rs`.

use std::collections::BTreeMap;
use std::panic::Location;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::OnceLock;

include!("site_rules.in");

/// The build's complete map of `.lock_or_recover()` sites: `(file, line, Site::code)`,
/// generated by `build.rs` from the same rules ([`classify_text`]) over every source file
/// it builds. A native build cannot read source files on the live thread, and does not
/// need to: the comparison thread looks each noted location up here.
mod generated {
    include!(concat!(env!("OUT_DIR"), "/dictation_lock_sites.rs"));
}

/// The build's map (the generated table), for tests that check it against the source.
pub(crate) fn site_map() -> &'static [(&'static str, u32, u8)] {
    generated::SITES
}

/// What the acquisition at `at` is, from the build's map. A location the map does not
/// name (`Unmapped`) is not assumed to be anything: it is reported as unclassified.
pub(crate) fn lookup(at: &Location<'_>) -> Site {
    generated::SITES
        .iter()
        .find(|(file, line, _)| *line == at.line() && at.file().ends_with(file))
        .map_or(Site::Unmapped, |(_, _, code)| Site::from_code(*code))
}

/// What the acquisition at `at` is, by reading the source file (test builds: the replay
/// applies it in the guard). Call it off the live path.
pub(crate) fn classify(at: &Location<'_>) -> Site {
    let file = at.file();
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let name = std::path::Path::new(file);
    let Some(text) = [name.to_path_buf(), manifest.join(name)]
        .into_iter()
        .chain(
            name.strip_prefix("app/src-tauri")
                .ok()
                .map(|rest| manifest.join(rest)),
        )
        .find_map(|path| std::fs::read_to_string(path).ok())
    else {
        // Test files need no source to be known as test code.
        return match classify_text(file, "", 1) {
            Site::Test => Site::Test,
            _ => Site::Unmapped,
        };
    };
    classify_text(file, &text, at.line() as usize)
}

// ------------------------------------------------------ the lock-free acquisition table

/// Distinct acquisition sites the table can hold. The app has about 125 (the build's map
/// counts them); twice that leaves room to grow. A full table
/// counts the excess in [`overflow`], which the summary reports as unclassified.
const SLOTS: usize = 256;

struct Slot {
    /// A non-zero hash of the site (file and line); 0 is a free slot.
    key: AtomicU64,
    count: AtomicU64,
    /// Written once, by the thread that claimed the slot; read by the comparison thread.
    at: OnceLock<&'static Location<'static>>,
}

#[allow(clippy::declare_interior_mutable_const)]
const FREE: Slot = Slot {
    key: AtomicU64::new(0),
    count: AtomicU64::new(0),
    at: OnceLock::new(),
};
static TABLE: [Slot; SLOTS] = [FREE; SLOTS];
static OVERFLOW: AtomicU64 = AtomicU64::new(0);

fn key_of(at: &Location<'_>) -> u64 {
    // FNV-1a over the file and the line: stable within a process, never 0.
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in at.file().bytes().chain(at.line().to_le_bytes()) {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    hash | 1
}

/// Note one acquisition of D at `at`: bounded probing over atomics, no allocation, no
/// lock, no wait. The live thread's whole cost.
pub(crate) fn note(at: &'static Location<'static>) {
    let key = key_of(at);
    let start = (key as usize) % SLOTS;
    for step in 0..SLOTS {
        let slot = &TABLE[(start + step) % SLOTS];
        match slot
            .key
            .compare_exchange(0, key, Ordering::AcqRel, Ordering::Acquire)
        {
            Ok(_) => {
                let _ = slot.at.set(at);
                slot.count.fetch_add(1, Ordering::Relaxed);
                return;
            }
            Err(found) if found == key => {
                slot.count.fetch_add(1, Ordering::Relaxed);
                return;
            }
            Err(_) => {}
        }
    }
    OVERFLOW.fetch_add(1, Ordering::Relaxed);
}

/// Acquisitions the table had no slot for.
pub(crate) fn overflow() -> u64 {
    OVERFLOW.load(Ordering::Relaxed)
}

/// Every site noted so far with its count. A slot claimed a moment ago has its location
/// published a few instructions later: this thread (never a live one) waits a bounded time
/// for it, and returns the count of a slot whose location never shows separately, so no
/// acquisition is left out of the snapshot.
pub(crate) fn snapshot() -> (Vec<(&'static Location<'static>, u64)>, u64) {
    let mut sites = Vec::new();
    let mut unpublished = 0_u64;
    for slot in TABLE.iter() {
        if slot.key.load(Ordering::Acquire) == 0 {
            continue;
        }
        let mut at = slot.at.get();
        for _ in 0..1000 {
            if at.is_some() {
                break;
            }
            std::thread::yield_now();
            at = slot.at.get();
        }
        match at {
            Some(at) => sites.push((*at, slot.count.load(Ordering::Acquire))),
            None => unpublished += slot.count.load(Ordering::Acquire),
        }
    }
    (sites, unpublished)
}

/// One snapshot of the table (D-S2c-15 review, round 3).
#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Report {
    /// Every acquisition noted, in the table or past its end.
    pub noted: u64,
    /// The non-family part of `noted`, by `file:line`.
    pub non_family: BTreeMap<String, u64>,
    /// The part of `noted` the build's map does not name (or the table could not hold).
    pub unclassified: u64,
}

impl Report {
    /// Acquisitions that are decision-section entries: all but the named non-family reads.
    /// From one snapshot, so it never falls below the entries' share of it.
    pub(crate) fn family_entries(&self) -> u64 {
        self.noted
            .saturating_sub(self.non_family.values().sum::<u64>())
    }
}

/// Look every noted site up once (the comparison thread calls this at each summary write;
/// it reads no file).
pub(crate) fn report() -> Report {
    let (sites, unpublished) = snapshot();
    let past_the_end = overflow() + unpublished;
    let mut report = Report {
        noted: past_the_end,
        unclassified: past_the_end,
        ..Report::default()
    };
    for (at, count) in sites {
        report.noted += count;
        match lookup(at) {
            Site::NonFamily => {
                *report
                    .non_family
                    .entry(format!("{}:{}", at.file(), at.line()))
                    .or_default() += count;
            }
            Site::Unmapped => report.unclassified += count,
            Site::Test | Site::Family => {}
        }
    }
    report
}
