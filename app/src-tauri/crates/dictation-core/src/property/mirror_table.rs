//! The supervisor mirror table (D-S2b-9 (a), D-S2b-15): model step -> the
//! `audio_lifecycle.rs` function it mirrors. Pure data with no dependency on the
//! model, so the app crate's pin test includes this file by path
//! (`src/audio_lifecycle_mirror_tests.rs`) and checks the same table the harness runs:
//! the citations, the fragments and guards as tokens, and the whole-file pins of the
//! source. The checks that need the model (every message, worker event, timer and
//! supervisor step has a row) stay in `tests.rs`.

/// One row of the mirror table. The model reads only `step`; the app crate's pin test
/// (which includes this file) reads the rest.
#[allow(dead_code)]
#[derive(Clone, Copy, Debug)]
pub struct Mirror {
    /// The model step (a `Msg` / `WorkerEv` / `SupStep` / timer name).
    pub step: &'static str,
    /// The source file under `src/`: `audio_lifecycle.rs`, or `audio.rs` for the
    /// worker thread's own end.
    pub file: &'static str,
    /// The function in that file.
    pub function: &'static str,
    /// A fragment of source that must appear within the cited function (the test
    /// reads the source and the function is hash-pinned, so a citation that drifted or
    /// never matched fails). It must match **exactly once** in the function, so it is long enough
    /// (an arm pattern, the statement around it) to be unique. No line range is kept: the function's pin is the guard
    /// against an edit inside it, and the test prints the lines it matched.
    pub needle: &'static str,
    /// What the model does there.
    pub what: &'static str,
    /// The guard expressions of the cited code, each a fragment that must appear in the
    /// cited function: a model step is only as faithful as the condition it runs under, so
    /// a mutated guard (`is_none()` turned into `is_some()`, a dropped clause) fails the
    /// mirror test as well as the real test below (D-S2b-11 (c)).
    pub guards: &'static [&'static str],
    /// A test of the real supervisor in `audio_lifecycle.rs` that pins the behaviour by
    /// running it (the test must exist there).
    pub real_test: Option<&'static str>,
}

