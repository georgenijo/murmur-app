//! Settings presentation catalog. Durable schemas/defaults belong to murmur-core.
use serde_json::{Value, json};
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Page {
    General,
    Recording,
    Customize,
    Delivery,
    Meetings,
    Text,
    Ai,
    Modes,
    Appearance,
    Performance,
    Diagnostics,
    Transcription,
    Shortcuts,
}
impl Page {
    pub const NAV: [Self; 11] = [
        Self::General,
        Self::Recording,
        Self::Customize,
        Self::Delivery,
        Self::Meetings,
        Self::Text,
        Self::Ai,
        Self::Modes,
        Self::Appearance,
        Self::Performance,
        Self::Diagnostics,
    ];
    pub fn id(self) -> &'static str {
        match self {
            Self::General => "general",
            Self::Recording => "recording",
            Self::Customize => "customize",
            Self::Delivery => "delivery",
            Self::Meetings => "meetings",
            Self::Text => "text",
            Self::Ai => "ai",
            Self::Modes => "modes",
            Self::Appearance => "appearance",
            Self::Performance => "performance",
            Self::Diagnostics => "diagnostics",
            Self::Transcription => "ai-transcription",
            Self::Shortcuts => "shortcuts",
        }
    }
    pub fn label(self) -> &'static str {
        match self {
            Self::General => "General",
            Self::Recording => "Recording",
            Self::Customize => "Customize",
            Self::Delivery => "Delivery",
            Self::Meetings => "Meetings",
            Self::Text => "Text & vocabulary",
            Self::Ai => "AI & models",
            Self::Modes => "Modes",
            Self::Appearance => "Appearance",
            Self::Performance => "Performance Lab",
            Self::Diagnostics => "Diagnostics",
            Self::Transcription => "Speech-to-text",
            Self::Shortcuts => "Keyboard shortcuts",
        }
    }
    pub fn resolve(id: &str) -> Self {
        match id {
            "dictation" => Self::Recording,
            "model" | "transcription" => Self::Transcription,
            "benchmark" => Self::Performance,
            "text-vocabulary" => Self::Text,
            "app" => Self::General,
            _ => Self::NAV
                .into_iter()
                .chain([Self::Transcription, Self::Shortcuts])
                .find(|p| p.id() == id)
                .unwrap_or(Self::General),
        }
    }
    pub fn has_advanced(self) -> bool {
        matches!(
            self,
            Self::General
                | Self::Recording
                | Self::Delivery
                | Self::Meetings
                | Self::Text
                | Self::Transcription
        )
    }
}
#[derive(Clone, Copy)]
pub enum Kind {
    Toggle,
    Choice(&'static [(&'static str, &'static str)]),
    Number(i64, i64),
    Range(i64, i64, i64, &'static str),
    Folder,
}
#[derive(Clone, Copy)]
pub struct Row {
    pub key: &'static str,
    pub target: &'static str,
    pub page: Page,
    pub label: &'static str,
    pub detail: &'static str,
    pub kind: Kind,
    pub advanced: bool,
    pub parent: Option<&'static str>,
    pub capture_locked: bool,
}
impl Row {
    pub fn visible(self, settings: &Value) -> bool {
        self.parent.is_none_or(|k| settings[k] == true)
            && (self.key != "hotkeyMissFeedback" || settings["recordingMode"] != "hold_down")
    }
    pub fn reveal(self, settings: &Value) -> &'static str {
        if let Some(k) = self.parent
            && settings[k] != true
        {
            return k;
        }
        if self.key == "hotkeyMissFeedback" && settings["recordingMode"] == "hold_down" {
            return "recordingMode";
        }
        self.key
    }
    pub fn parse(self, text: &str) -> Option<Value> {
        match self.kind {
            Kind::Number(min, max) | Kind::Range(min, max, _, _) => text
                .parse::<i64>()
                .ok()
                .filter(|v| (*v >= min) && (*v <= max))
                .map(|v| json!(v)),
            Kind::Choice(options) => options.iter().find(|(v, _)| *v == text).map(|_| {
                let default = murmur_core::state::settings_defaults();
                if default[self.key].is_number() {
                    json!(text.parse::<i64>().expect("numeric options"))
                } else if text == "disabled" && self.key == "pasteLastShortcut" {
                    Value::Null
                } else {
                    json!(text)
                }
            }),
            _ => None,
        }
    }
}
